def main() -> int:
    mechanisms = _mechanisms()
    by_class: Dict[str, int] = {}
    for m in mechanisms:
        c = str(m["classification"])
        by_class[c] = by_class.get(c, 0) + 1
    report = {
        "generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "evidence_scope": "local_source_classification",
        "classification_legend": {
            "A": "PHYSICAL_OPERATOR_DEFINING",
            "B": "SOLVER_TARGETING_OR_NUMERICAL_POLICY",
            "C": "EVIDENCE_PRESERVATION",
            "D": "POST_REPLAY_PHYSICAL_VERDICT_GATE",
            "E": "PRE_REPLAY_FILTER_OR_SELECTION",
            "F": "PRODUCTION_ONLY_OR_LEGACY",
        },
        "mechanisms": mechanisms,
        "summary": {
            "count": len(mechanisms),
            "by_classification": by_class,
            "filter_classification_complete": True,
        },
        "no_eigensolve_executed": True,
    }
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(report, indent=2), encoding="utf-8")
    lines = [
        "# Clean adjudication filter and policy classification",
        "",
        f"Generated: {report['generated_utc']}",
        "",
        "## Summary",
        "",
        f"- mechanisms classified: {len(mechanisms)}",
        f"- by class: {json.dumps(by_class)}",
        "",
        "## Focal mechanisms",
        "",
    ]
    for m in mechanisms:
        lines.append(
            f"- **{m['mechanism_id']}** [{m['classification']}] → {m['required_action']}"
        )
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[filter_classification] count={len(mechanisms)} wrote {OUT_JSON}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
